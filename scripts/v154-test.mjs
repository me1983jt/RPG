// v15.4: Greenville / Moosehead Lake unlock (questFlags harmony.hasMooseheadMap === true AND harmony.ferry === 'fixed', via leaveTown),
// the moosehead_map item, and the landing area (lake, cabins, safe zone, no town iframe).
import { boot } from "./v4-lib.mjs";
const url = process.argv[2] || "http://127.0.0.1:8112/";
const { browser, page, errs, T, begin } = await boot(url, { vw: 412, vh: 915, v14: true, safe: true });
let fail = 0; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fail++; };
await begin(); await T("v14Set", { st: 5 });
await page.evaluate(() => { window.__controlsTest.choose?.("close"); });
const leave = (flags, inventory) => page.evaluate(([f, inv]) => { const t = window.__controlsTest; t.v15Open("harmony"); return t.town143Msg({ type: "leaveTown", exit: "town", state: { questFlags: f, ...(inv ? { inventory: inv } : {}) } }); }, [flags, inventory]);
let w = await T("v154Wm");
ok(!w.open && w.locked.includes("greenville") && w.loc === null, "Greenville hidden at start");
let g = await T("v154Go");
ok(g.map !== 7 && /lake map/.test(g.warn), `locked: can't go in (${g.warn})`);
const inv = await page.evaluate(() => window.__controlsTest.v15State().inventory);
await leave({ "harmony.hasMooseheadMap": true }, [...inv, { id: "moosehead_map", qty: 1 }]);
w = await T("v154Wm");
ok(w.bag.length === 1 && w.bag[0] === 1, `moosehead_map accepted into the pack (${JSON.stringify(w.bag)})`);
ok(/\/game\/items\/moosehead_map\.png/.test(w.icon), `icon ${w.icon}`);
const r = await page.evaluate((src) => fetch(src).then((x) => x.ok && x.headers.get("content-type")?.includes("image")), w.icon);
ok(r, "icon file is served");
ok(!w.open && w.locked.includes("greenville"), "map alone doesn't unlock");
await leave({ "harmony.ferry": "broken" });
ok(!(await T("v154Wm")).open, "ferry not fixed: still locked");
await leave({ "harmony.ferry": "fixed", "harmony.hasMooseheadMap": false });
ok(!(await T("v154Wm")).open, "ferry fixed but map flag false: still locked");
await leave({ "harmony.hasMooseheadMap": true, "harmony.ferry": "fixed" });
w = await T("v154Wm");
ok(w.open && !w.locked.length && w.loc === "greenville", "both flags: Greenville unlocked");
g = await T("v154Go");
ok(g.map === 7 && /Greenville/.test(g.name), `travel lands at ${g.name} (map ${g.map})`);
ok(g.shacks >= 3, `cabins: ${g.shacks}`);
await page.waitForTimeout(1500);
const sz = await T("v15Safe");
ok(sz.here === "greenville" || g.safe === "greenville", `landing is a safe zone (${sz.here} / ${JSON.stringify(sz.zones.map((z) => z.id))})`);
ok(g.hostiles === 0, `no hostiles (${g.hostiles})`);
ok(!g.town, "no town iframe");
await page.waitForTimeout(600);
await page.screenshot({ path: (process.env.V154OUT || "/tmp/") + "v154-greenville.png" });
ok(errs.length === 0, `no errors ${errs.slice(0, 3).join(" | ")}`);
console.log(fail ? `${fail} FAILED` : "ALL PASS");
await browser.close();
process.exit(fail ? 1 : 0);
