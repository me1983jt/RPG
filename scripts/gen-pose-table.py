"""Builds src/game/pose-table.ts: per 8-direction sheet, which cell to draw when standing still
(cleanest feet-together frame, upright) and which row to walk with (skipping rows whose art is slanted
or wrongly sized). Run after any person sheet changes."""
from PIL import Image
import numpy as np, glob, json, os
D = "S SW W NW N NE E SE".split()
def met(cell):
    a = np.array(cell)[:, :, 3] > 40; ys, xs = np.nonzero(a)
    if not len(ys): return None
    t, b = ys.min(), ys.max(); h = b - t
    cx = lambda y0, y1: xs[(ys >= y0) & (ys <= y1)].mean()
    feet = np.nonzero(a[int(b - h * .06):b + 1].any(0))[0]
    return dict(lean=float(cx(b - h * .12, b) - cx(t, t + h * .15)), spread=int(feet.max() - feet.min()), w=int(xs.max() - xs.min()), h=int(h))
out = {}
root = "public/game"
names = ["hero", "villager"] + [os.path.basename(f)[:-4] for f in sorted(glob.glob(f"{root}/npc-*.png"))]
for n in names:
    im = Image.open(f"{root}/{n}.png").convert("RGBA")
    if im.size != (352, 992): continue
    M = [[met(im.crop((c * 88, r * 124, c * 88 + 88, r * 124 + 124))) for c in range(4)] for r in range(8)]
    sw = np.median([m["w"] for m in M[0]])
    bad = []
    for r in range(8):
        lean = np.median([abs(m["lean"]) for m in M[r]]); wid = np.median([m["w"] for m in M[r]])
        bad.append(bool(lean > 8 or (r == 4 and wid > sw * 1.35)))
    walk, idle = [], []
    side = {1: 2, 3: 2, 5: 6, 7: 6, 0: 0, 2: 2, 4: 4, 6: 6}
    alt = {4: [3, 5, 2, 6], 0: [1, 7, 2, 6]}
    for r in range(8):
        wr = r
        if bad[r]:
            for c in ([side[r]] if side[r] != r else []) + alt.get(r, []):
                if not bad[c]: wr = c; break
        walk.append(wr)
        cand = [r] + ([0] if r in (1, 7, 2, 6) else [4] if r in (3, 5) else [])
        if r == 4: cand += [0]
        best = None
        for c in cand:
            if bad[c]: continue
            f = min(range(4), key=lambda i: M[c][i]["spread"])
            if M[c][f]["spread"] <= 30: best = [c, f]; break
        if not best:
            c = 0; best = [c, min(range(4), key=lambda i: M[c][i]["spread"])]
        idle.append(best)
    # walk cycle per row: drop a feet-together stand frame from the stride (Grok painted frame 0 of
    # some side rows as a stand); keep all 4 when every frame is a stride
    cycle = []
    for r in range(8):
        wr = walk[r]
        strides = [i for i in range(4) if M[wr][i]["spread"] > 30]
        cycle.append(strides if len(strides) == 3 else [0, 1, 2, 3])
    out[n] = {"walk": walk, "idle": idle, "cycle": cycle}
    print(n, "bad", [D[i] for i in range(8) if bad[i]], "walk", walk, "idle", idle)
with open("src/game/pose-table.ts", "w") as f:
    f.write("// Generated by scripts/gen-pose-table.py. Do not edit by hand.\n")
    f.write("export const POSE: Record<string, { walk: number[]; idle: number[][]; cycle: number[][] }> = " + json.dumps(out) + ";\n")
