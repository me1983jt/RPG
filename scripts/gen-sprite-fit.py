# Visible-figure fraction of each 8-row sheet cell (tallest of S/W/E rows), for real-world sizing.
from PIL import Image
import numpy as np, glob, os, json
out={}
for p in sorted(glob.glob("public/game/*.png")):
    n=os.path.basename(p)[:-4]
    im=Image.open(p)
    if im.size!=(352,992) or n.endswith("-dead") or n.endswith("-atk") or n.endswith("-portrait"): continue
    a=np.array(im.convert("RGBA"))[:,:,3]>40; ch=124; best=0
    for r in (0,2,6):
        ys=np.nonzero(a[r*ch:(r+1)*ch].any(1))[0]
        if len(ys): best=max(best,(ys.max()-ys.min()+1)/ch)
    if best: out[n]=round(best,3)
open("src/game/sprite-fit.ts","w").write("// generated by scripts/gen-sprite-fit.py\nexport const SPRITE_FIT: Record<string, number> = "+json.dumps(out,indent=1)+";\n")
print(len(out)); print(out)
