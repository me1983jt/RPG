for (const t of ["rifle", "trail", "doctor"]) await page.locator(`[data-tag="${t}"]`).click();
await page.locator('[data-trait2="armyvet"]').click();
await page.getByTestId("cc-sex-female").click(); await page.locator('[data-bg="lobsterman"]').click(); await page.locator('[data-tint="spruce"]').click();
await page.screenshot({ path: `${dir}/5-sheet-custom.png` });
ok(await page.getByTestId("cc-done").isEnabled(), "done enabled");
await page.getByTestId("cc-random").click(); await page.waitForTimeout(200);
await page.screenshot({ path: `${dir}/6-sheet-random.png` });
