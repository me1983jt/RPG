// take Justin
await page.getByTestId("take-justin").click(); await page.waitForTimeout(4000);
await page.evaluate(() => window.__maineSave?.());
const st = await page.evaluate(() => { const all = Object.entries(localStorage).map(([k, v]) => { try { return [k, JSON.parse(v)]; } catch { return [k, null]; } }); const hit = all.find(([, v]) => v && v.hero15134); const s = hit?.[1] ?? {}; return { key: hit?.[0], bag: JSON.stringify(s.bag ?? s.player?.bag ?? []).slice(0, 400), traits2: s.traits2, perks: s.perks, hero: s.hero15134, keys: all.map(([k]) => k) }; });
console.log("justin save", JSON.stringify(st));
ok(/toolkit/.test(st.bag) && /shells/.test(st.bag) && (st.traits2 ?? []).includes("armyvet") && JSON.stringify(st.perks ?? "").includes("fieldfix"), "Justin: rifle ammo + toolkit, Army Vet, Field Fix saved");
await page.screenshot({ path: `${dir}/7-justin-start.png` });
ok(!errs.length, `no page errors ${errs.slice(0, 3).join(" | ")}`);
await b.close(); process.exit(fail ? 1 : 0);
