// v15.13.4: new character creation (premade cards + one character sheet), Justin/Sarah start + recruit swap.
import { chromium } from "playwright";
const dir = process.argv[2] || "/workspace/maine-rpg/shots/v15134";
const url = process.argv[3] || "http://127.0.0.1:8112/";
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const ctx = await b.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = []; page.on("pageerror", (e) => errs.push(String(e)));
await page.addInitScript(() => { window.__v13Quiet = true; window.__safeOff = true; window.__tbOff = true; });
await page.goto(url, { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear()); await page.reload({ waitUntil: "networkidle" }); await page.waitForTimeout(2500);
let fail = 0; const ok = (v, m) => { console.log((v ? "PASS " : "FAIL ") + m); if (!v) fail++; };
await page.screenshot({ path: `${dir}/1-pick.png` });
ok(await page.getByTestId("card-justin").isVisible() && await page.getByTestId("card-sarah").isVisible() && await page.getByTestId("card-own").isVisible(), "three cards");
await page.getByTestId("modify-justin").click(); await page.waitForTimeout(400);
await page.screenshot({ path: `${dir}/2-sheet-justin.png` });
await page.getByTestId("cc-cancel").click();
await page.getByTestId("modify-sarah").click(); await page.waitForTimeout(400);
await page.locator('[data-tag="trail"]').click(); await page.locator('[data-tag="trail"]').click();
await page.screenshot({ path: `${dir}/3-sheet-sarah.png` });
await page.getByTestId("cc-cancel").click();
await page.getByTestId("create-own").click(); await page.waitForTimeout(300);
await page.screenshot({ path: `${dir}/4-sheet-blank.png` });
ok(await page.getByTestId("cc-done").isDisabled(), "done disabled until points/tags spent");
await page.fill("#wanderer-name", "Hazel");
